// Builds:
//   src/samples.js        example notes bundled for the browser (from samples/*.md)
//   index.html            the app, loading files from src/ (use locally or on GitHub Pages)
//   dist/actionlens.html  one self-contained file with everything inlined (easy to share)
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');

const samples = [
  { file: 'sprint-2-review.md', label: 'Sprint 2 review (project team)' },
  { file: 'client-requirements-call.md', label: 'Client requirements call' }
].map((s) => ({ label: s.label, text: read('samples/' + s.file) }));
const samplesJs = '// Generated by scripts/build-single-file.js from samples/*.md\nwindow.ACTIONLENS_SAMPLES = ' + JSON.stringify(samples, null, 2) + ';\n';
fs.writeFileSync(path.join(root, 'src/samples.js'), samplesJs);

const fonts = '<link rel="preconnect" href="https://fonts.googleapis.com"><link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>' +
  '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Figtree:wght@400;500;600;700;800&family=IBM+Plex+Mono:wght@400;500&display=swap">';
const head = '<meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">' +
  '<title>ActionLens</title>' +
  '<meta name="description" content="Turn meeting notes into action items, owners, due dates, decisions and risks.">';
const body = read('src/body.html');

const index = '<!doctype html>\n<html lang="en">\n<head>\n' + head + '\n' + fonts + '\n<link rel="stylesheet" href="src/styles.css">\n</head>\n<body>\n' + body +
  '<script src="src/samples.js"></script>\n<script src="src/extractor.js"></script>\n<script src="src/app.js"></script>\n</body>\n</html>\n';
fs.writeFileSync(path.join(root, 'index.html'), index);

const inline = (code) => '<script>\n' + code.replace(/<\/script/gi, '<\\/script') + '\n</script>\n';
const single = '<!doctype html>\n<html lang="en">\n<head>\n' + head + '\n' + fonts + '\n<style>\n' + read('src/styles.css') + '\n</style>\n</head>\n<body>\n' +
  body + inline(samplesJs) + inline(read('src/extractor.js')) + inline(read('src/app.js')) + '</body>\n</html>\n';
fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
fs.writeFileSync(path.join(root, 'dist/actionlens.html'), single);
console.log('Built index.html, src/samples.js and dist/actionlens.html (' + Math.round(single.length / 1024) + ' KB)');
